export function getPresetPermissionsForRole(role: UserRole): UserPermissions {
  if (role === 'admin') return { ...ADMIN_PERMISSIONS };
  if (role === 'accountant') return { ...ACCOUNTANT_PERMISSIONS };
  return { ...CASHIER_PERMISSIONS };
}

export function getRoleDisplayLabel(role: UserRole): string {
  if (role === 'admin') return 'مدير النظام';
  if (role === 'accountant') return 'محاسب';
  if (role === 'cashier') return 'كاشير';
  return 'كاشير / موظف';
}

